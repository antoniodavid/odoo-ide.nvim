local M = {}
local doodba = require("odoo-ide.doodba")

local function escape_toml_string(str)
  return '"' .. str:gsub('\\', '\\\\'):gsub('"', '\\"') .. '"'
end

local function format_toml_array_multiline(arr, indent)
  indent = indent or "    "
  if #arr == 0 then
    return "[]"
  end
  local lines = { "[" }
  for _, v in ipairs(arr) do
    table.insert(lines, indent .. escape_toml_string(v) .. ",")
  end
  table.insert(lines, "]")
  return table.concat(lines, "\n")
end

local function get_relative_path(full_path, base_path)
  if full_path:sub(1, #base_path) == base_path then
    local rel = full_path:sub(#base_path + 1)
    if rel:sub(1, 1) == "/" then
      rel = rel:sub(2)
    end
    return "./" .. rel
  end
  return full_path
end

function M.generate_config(opts)
  opts = opts or {}

  local root = doodba.find_root()
  if not root then
    return nil, "Not in a Doodba project"
  end

  local src_path = root .. "/odoo/custom/src"
  local odoo_path = doodba.find_odoo_path(src_path)

  if not odoo_path then
    return nil, "Odoo source not found in " .. src_path
  end

  local paths = doodba.get_paths({
    include_all_repos = opts.include_all_repos
  })

  local use_relative = opts.use_relative_paths ~= false
  local addons_paths = {}

  for _, path in ipairs(paths) do
    -- Filter out odoo core path itself if it ended up in addons paths (it shouldn't, but safe check)
    if path ~= odoo_path then
      local final_path = use_relative and get_relative_path(path, root) or path
      table.insert(addons_paths, final_path)
    end
  end

  local odoo_path_str = use_relative and get_relative_path(odoo_path, root) or odoo_path

  local profile_name = opts.profile_name or "main"
  local python_path = opts.python_path
  local additional_stubs = opts.additional_stubs or {}
  local refresh_mode = opts.refresh_mode or "adaptive"
  local auto_refresh_delay = opts.auto_refresh_delay or 1000

  local lines = {
    "# Auto-generated by odoo-ide.nvim",
    "# Regenerate with :OdooGenerateConfig",
    "",
    "[[config]]",
    "name = " .. escape_toml_string(profile_name),
    "odoo_path = " .. escape_toml_string(odoo_path_str),
    "addons_paths = " .. format_toml_array_multiline(addons_paths),
    "",
    "# Performance",
    'refresh_mode = "' .. refresh_mode .. '"',
    "auto_refresh_delay = " .. auto_refresh_delay,
    "file_cache = true",
    "",
    "# Diagnostics",
    'diag_missing_imports = "all"',
    "ac_filter_model_names = true",
  }

  if python_path then
    table.insert(lines, "python_path = " .. escape_toml_string(python_path))
  end

  if #additional_stubs > 0 then
    table.insert(lines, "additional_stubs = " .. format_toml_array_multiline(additional_stubs))
  end

  table.insert(lines, "")

  return table.concat(lines, "\n"), nil
end

function M.write_config(opts)
  opts = opts or {}

  local root = doodba.find_root()
  if not root then
    return false, "Not in a Doodba project"
  end

  local output_path = opts.output_path or root
  local config_file = output_path .. "/odools.toml"

  if vim.fn.filereadable(config_file) == 1 and not opts.force_regenerate then
    return true, "Config already exists at " .. config_file
  end

  local content, err = M.generate_config(opts)
  if not content then
    return false, err
  end

  local file = io.open(config_file, "w")
  if not file then
    return false, "Failed to open " .. config_file .. " for writing"
  end

  file:write(content)
  file:close()

  return true, config_file
end

function M.get_config_path()
  local root = doodba.find_root()
  if not root then
    return nil
  end

  local config_file = root .. "/odools.toml"
  if vim.fn.filereadable(config_file) == 1 then
    return config_file
  end

  return nil
end

function M.is_config_outdated(config_file)
  local file = io.open(config_file, "r")
  if not file then return false end
  local content = file:read("*a")
  file:close()

  -- Check for absolute paths (odoo_path starting with /)
  if content:match('odoo_path%s*=%s*"/') then
    return true
  end

  -- Check for double slashes in paths (potential bug from old version)
  -- We look for // but not inside protocols like http://
  if content:match('[^:]//') or content:match('^//') then
    return true
  end

  return false
end

function M.ensure_config(opts)
  opts = opts or {}
  opts.force_regenerate = opts.force_regenerate ~= false

  local existing = M.get_config_path()
  if not opts.force_regenerate and existing then
    -- Check if existing config uses absolute paths (deprecated)
    local content = vim.fn.readfile(existing)
    local has_absolute = false
    for _, line in ipairs(content) do
      -- Check for absolute paths in odoo_path or addons_paths
      -- Look for paths starting with "/" inside quotes
      if line:match('path%s*=%s*["\']/') or line:match('^%s*["\']/') then
        has_absolute = true
        break
      end
    end

    if has_absolute then
      vim.notify("odoo-ide: Detected legacy absolute paths in odools.toml. Regenerating with relative paths...", vim.log.levels.WARN)
      opts.force_regenerate = true
    else
      return existing
    end
  end

  local success, result = M.write_config(opts)
  if success then
    if vim.fn.filereadable(result) == 1 then
      return result
    end
    return M.get_config_path()
  end

  return nil
end

function M.setup_commands()
  vim.api.nvim_create_user_command("OdooGenerateConfig", function(cmd_opts)
    local opts = {
      force_regenerate = true,
      include_all_repos = cmd_opts.args:match("all") ~= nil,
    }

    local success, result = M.write_config(opts)
    if success then
      if result:match("already exists") then
        vim.notify("odoo-ide: " .. result, vim.log.levels.INFO)
      else
        vim.notify("odoo-ide: Generated " .. result, vim.log.levels.INFO)
      end
    else
      vim.notify("odoo-ide: " .. result, vim.log.levels.ERROR)
    end
  end, {
    bang = true,
    nargs = "?",
    desc = "Generate odools.toml for current Doodba project",
  })

  vim.api.nvim_create_user_command("OdooShowConfig", function()
    local content, err = M.generate_config({ include_all_repos = true })
    if content then
      vim.cmd("new")
      vim.bo.buftype = "nofile"
      vim.bo.bufhidden = "wipe"
      vim.bo.filetype = "toml"
      vim.api.nvim_buf_set_name(0, "odools.toml (preview)")
      vim.api.nvim_buf_set_lines(0, 0, -1, false, vim.split(content, "\n"))
    else
      vim.notify("odoo-ide: " .. (err or "Failed to generate config"), vim.log.levels.ERROR)
    end
  end, {
    desc = "Show generated odools.toml in a buffer",
  })
end

return M
