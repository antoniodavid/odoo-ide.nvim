local M = {}
local project = require("odoo-ide.project")
local utils = require("odoo-ide.utils")

local function escape_toml_string(str)
  return '"' .. str:gsub('\\', '\\\\'):gsub('"', '\\"') .. '"'
end

local function format_toml_array_multiline(arr, indent)
  indent = indent or "    "
  if #arr == 0 then
    return "[]"
  end
  local lines = { "[" }
  for _, v in ipairs(arr) do
    table.insert(lines, indent .. escape_toml_string(v) .. ",")
  end
  table.insert(lines, "]")
  return table.concat(lines, "\n")
end

function M.generate_config(opts)
  opts = opts or {}

  local current = opts.project or project.get()
  if not current then
    return nil, "Not in an Odoo project"
  end

  if not current.odoo_path then
    return nil, "Odoo source not found for this project"
  end

  local paths = project.paths(current, {
    include_all_repos = opts.include_all_repos,
  })

  local use_relative = opts.use_relative_paths ~= false
  local addons_paths = {}

  for _, path in ipairs(paths) do
    -- The core path is declared through `odoo_path`, never as an addon path.
    if path ~= current.odoo_path then
      local final_path = use_relative and utils.relative_path(path, current.root) or path
      table.insert(addons_paths, final_path)
    end
  end

  local odoo_path_str = use_relative and utils.relative_path(current.odoo_path, current.root) or current.odoo_path

  local profile_name = opts.profile_name or "main"
  local python_path = opts.python_path
  local additional_stubs = opts.additional_stubs or {}
  local auto_refresh_delay = opts.auto_refresh_delay or 1000

  local lines = {
    "# Auto-generated by odoo-ide.nvim",
    "",
    "[[config]]",
    "name = " .. escape_toml_string(profile_name),
    "odoo_path = " .. escape_toml_string(odoo_path_str),
    "addons_paths = " .. format_toml_array_multiline(addons_paths),
    "",
    "# Performance",
    "auto_refresh_delay = " .. auto_refresh_delay,
    "file_cache = true",
    "",
    "# Diagnostics",
    'diag_missing_imports = "all"',
    "ac_filter_model_names = true",
  }

  if python_path then
    table.insert(lines, "python_path = " .. escape_toml_string(python_path))
  end

  if #additional_stubs > 0 then
    table.insert(lines, "additional_stubs = " .. format_toml_array_multiline(additional_stubs))
  end

  table.insert(lines, "")

  return table.concat(lines, "\n"), nil
end

---Write the configuration, skipping identical content.
---@param opts? table
---@return boolean ok
---@return string|nil path_or_error
---@return boolean|nil changed
function M.write_config(opts)
  opts = opts or {}

  local current = opts.project or project.get()
  if not current then
    return false, "Not in an Odoo project"
  end

  local output_path = opts.output_path or project.config_dir(current)
  local config_file = output_path .. "/odools.toml"

  local content, err = M.generate_config(opts)
  if not content then
    return false, err
  end

  local ok, changed = utils.write_if_changed(config_file, content)
  if not ok then
    return false, changed
  end

  return true, config_file, changed
end

---Existing odools.toml for the project, if any.
---@param current? table
---@param opts? { output_path?: string }
---@return string|nil
function M.get_config_path(current, opts)
  opts = opts or {}
  current = current or project.get()
  if not current then
    return nil
  end

  local config_file = (opts.output_path or project.config_dir(current)) .. "/odools.toml"
  if vim.fn.filereadable(config_file) == 1 then
    return config_file
  end

  return nil
end

---Generate the configuration when it is missing or its content is stale.
---@param opts? table
---@return string|nil path
function M.ensure_config(opts)
  opts = opts or {}

  local current = opts.project or project.get()
  if not current or not current.odoo_path then
    return nil
  end

  local ok, path = M.write_config(vim.tbl_extend("force", opts, { project = current }))
  if ok then
    return path
  end

  return M.get_config_path(current, opts)
end

function M.setup_commands()
  vim.api.nvim_create_user_command("OdooGenerateConfig", function(cmd_opts)
    local opts = {
      include_all_repos = cmd_opts.args:match("all") ~= nil,
    }

    local success, result = M.write_config(opts)
    if success then
      vim.notify("odoo-ide: Generated " .. result, vim.log.levels.INFO)
    else
      vim.notify("odoo-ide: " .. result, vim.log.levels.ERROR)
    end
  end, {
    bang = true,
    nargs = "?",
    desc = "Generate odools.toml for the current Odoo project",
  })

  vim.api.nvim_create_user_command("OdooShowConfig", function()
    local content, err = M.generate_config({ include_all_repos = true })
    if content then
      vim.cmd("new")
      vim.bo.buftype = "nofile"
      vim.bo.bufhidden = "wipe"
      vim.bo.filetype = "toml"
      vim.api.nvim_buf_set_name(0, "odools.toml (preview)")
      vim.api.nvim_buf_set_lines(0, 0, -1, false, vim.split(content, "\n"))
    else
      vim.notify("odoo-ide: " .. (err or "Failed to generate config"), vim.log.levels.ERROR)
    end
  end, {
    desc = "Show the generated odools.toml in a buffer",
  })
end

return M
